function wireAdminReset() {
  document.getElementById('btn-reset-data').addEventListener('click', function() {
    document.getElementById('confirm-body').textContent = 'This will delete all employees and reset all settings. Are you sure?';
    document.getElementById('confirm-modal').classList.add('open');
    document.getElementById('confirm-ok').onclick = function() {
      State.employees = generateSeedEmployees(State.regions.map(function(r) { return r.id; }));
      State.settings = { ...DEFAULT_SETTINGS };
      State.visibility = { ...DEFAULT_VISIBILITY };
      DataStore.set(KEYS.employees, State.employees);
      DataStore.set(KEYS.settings, State.settings);
      DataStore.set(KEYS.visibility, State.visibility);
      renderAll();
      showToast('All data has been reset.', 'ok');
      document.getElementById('confirm-modal').classList.remove('open');
      document.getElementById('confirm-ok').onclick = null;
    };
  });
}

