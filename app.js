let bootstrapStarted = false;

function bootstrap() {
  // Guards against bootstrap() running twice — e.g. the timeout
  // fallback below firing while pullRemoteState() was still pending,
  // then pullRemoteState() finishing and triggering a second call.
  // Re-entering bootstrap() would call initMap() again on a Leaflet
  // container that's already initialized ("Map container is already
  // initialized"), so we bail out immediately on the second call.
  if (bootstrapStarted) return;
  bootstrapStarted = true;

  try {
    console.log('CPV Arabia Dashboard - Starting...');
    
    // Load data from localStorage
    const cachedVersion = DataStore.get(KEYS.geoVersion, null);
    const cacheIsStale = cachedVersion !== REGIONS_CACHE_VERSION;

    let storedGeo = DataStore.get(KEYS.geojson, null);
    let storedRegions = DataStore.get(KEYS.regions, null);
    const storedEmployees = DataStore.get(KEYS.employees, null);
    const storedSettings = DataStore.get(KEYS.settings, null);
    const storedVisibility = DataStore.get(KEYS.visibility, null);
    const storedLabels = DataStore.get(KEYS.labels, null);
    const storedBoundaryEdits = DataStore.get(KEYS.boundaryEdits, null);
    const storedRegionAggregates = DataStore.get(KEYS.regionAggregates, null);
    const storedCustomCharts = DataStore.get(KEYS.customCharts, null);
    const storedMapLabelPositions = DataStore.get(KEYS.mapLabelPositions, null);

    if (cacheIsStale) {
      // A previous session cached region geometry from an older/incorrect
      // KML parse. Discard it so the fixed geometry (live file or the
      // updated fallback below) is used instead of shadowing itself.
      console.log('Region cache is stale — reloading geometry from source.');
      storedGeo = null;
      storedRegions = null;
    }

    // Try to load KML
    let liveGeo = null;
    try {
      const xhr = new XMLHttpRequest();
      xhr.open('GET', 'regions.kml', false);
      xhr.send();
      if (xhr.status === 200) {
        const parsed = parseKMLToGeoJSON(xhr.responseText);
        if (parsed && parsed.features.length) liveGeo = parsed;
      }
    } catch (e) {
      console.warn('Could not load regions.kml, using fallback.', e);
    }

    State.geojson = liveGeo || storedGeo || DEFAULT_REGIONS_GEOJSON;
    // Merge additively — same reasoning as labels below — so a new
    // default field (e.g. logoDataUrl) added later is never silently
    // missing just because the person already has saved settings.
    State.settings = Object.assign({}, DEFAULT_SETTINGS, storedSettings || {});
    State.visibility = storedVisibility || DEFAULT_VISIBILITY;
    // Merge additively so new label keys added in future updates still
    // get a sensible default even if the person already customized others.
    State.labels = Object.assign({}, DEFAULT_LABELS, storedLabels || {});

    // Manual boundary edits made in the app (dragging vertices on the
    // map) are stored separately from the raw KML/geojson so they
    // survive re-loading regions.kml — they're re-applied on top of
    // whatever geometry the region name matches, even after a fresh
    // KML import.
    if (storedBoundaryEdits && Object.keys(storedBoundaryEdits).length) {
      State.geojson = {
        type: 'FeatureCollection',
        features: State.geojson.features.map(function(f) {
          var edit = storedBoundaryEdits[f.properties.id];
          if (edit) {
            return Object.assign({}, f, { geometry: { type: 'Polygon', coordinates: [edit] } });
          }
          return f;
        })
      };
    }
    State.boundaryEdits = storedBoundaryEdits || {};
    State.regionAggregates = storedRegionAggregates || {};
    State.customCharts = storedCustomCharts || [];
    State.mapLabelPositions = storedMapLabelPositions || {};

    // Build regions
    const existingRegionById = Object.fromEntries((storedRegions || []).map(r => [r.id, r]));
    State.regions = State.geojson.features.map(f => ({
      id: f.properties.id,
      name: f.properties.name || f.properties.id,
      description: existingRegionById[f.properties.id]?.description || ''
    }));

    // Load employees. storedEmployees is `null` only when the key was
    // never saved before (first run). If it's an array — even an empty
    // one, e.g. the person deleted every employee on purpose — that's
    // real saved state and must be respected, not treated as "no data"
    // and regenerated. (Previously this checked `.length`, so clearing
    // the list made the demo employees silently come back on reload.)
    if (storedEmployees !== null && !cacheIsStale) {
      State.employees = storedEmployees;
    } else {
      State.employees = generateSeedEmployees(State.regions.map(r => r.id));
      DataStore.set(KEYS.employees, State.employees);
    }

    // Save data
    DataStore.set(KEYS.geoVersion, REGIONS_CACHE_VERSION);
    DataStore.set(KEYS.regions, State.regions);
    DataStore.set(KEYS.geojson, State.geojson);
    if (!storedSettings) DataStore.set(KEYS.settings, State.settings);
    if (!storedVisibility) DataStore.set(KEYS.visibility, State.visibility);
    DataStore.set(KEYS.labels, State.labels);
    if (!storedRegionAggregates) DataStore.set(KEYS.regionAggregates, State.regionAggregates);
    if (!storedCustomCharts) DataStore.set(KEYS.customCharts, State.customCharts);
    if (!storedMapLabelPositions) DataStore.set(KEYS.mapLabelPositions, State.mapLabelPositions);

    // Initialize map if Leaflet is available
    if (typeof L !== 'undefined') {
      try {
        initMap();
      } catch (e) {
        console.warn('Map initialization failed:', e);
        document.getElementById('map').innerHTML = 
          '<div style="padding:40px;text-align:center;color:var(--ink-faint);">' +
          '<p style="font-size:16px;font-weight:600;">Map Unavailable</p>' +
          '<p style="font-size:13px;">Leaflet error: ' + e.message + '</p>' +
          '</div>';
      }
    } else {
      console.warn('Leaflet not available - map disabled');
      document.getElementById('map').innerHTML = 
        '<div style="padding:40px;text-align:center;color:var(--ink-faint);">' +
        '<p style="font-size:16px;font-weight:600;">Map Unavailable</p>' +
        '<p style="font-size:13px;">Leaflet library not loaded.</p>' +
        '</div>';
    }

    document.addEventListener('keydown', function(e) {
      if (e.key === 'Escape' && State.boundaryEditing) cancelBoundaryEdit();
    });

    // Wire everything
    wireNav();
    wireTopbar();
    wireEmployeeModal();
    wireBulkEditModal();
    wireConfirmModal();
    wireImportDuplicateModal();
    wireAdmin();
    wireEmployeeTableControls();
    wireEmployeesBulkActions();
    wireBuilderControls();
    renderAll();
    startClock();

    // Hide loading screen
    document.getElementById('loading-screen').style.opacity = '0';
    setTimeout(function() {
      document.getElementById('loading-screen').style.display = 'none';
    }, 320);

    State.initialized = true;
    console.log('CPV Arabia Dashboard - Ready!');

  } catch (err) {
    console.error('Bootstrap error:', err);
    showFatalLoadError(err.message || 'Unknown error during bootstrap.');
  }
}

