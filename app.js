/* ---------------------------------------------------------------------
   23. Toast notifications
------------------------------------------------------------------- */
function showToast(msg, type) {
  var wrap = document.getElementById('toast-wrap');
  var el = document.createElement('div');
  el.className = 'toast ' + (type === 'err' ? 'err' : 'ok');
  el.textContent = msg;
  wrap.appendChild(el);
  setTimeout(function() {
    el.style.opacity = '0';
    setTimeout(function() { el.remove(); }, 300);
  }, 2500);
}

