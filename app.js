function buildGeoLayer() {
  if (State.geoLayer) {
    State.map.removeLayer(State.geoLayer);
  }
  // Regions marked hidden (Admin → Regions → "Hide from map") keep
  // their data/employees intact but are skipped when drawing the map.
  var hiddenIds = {};
  State.regions.forEach(function(r) { if (r.hidden) hiddenIds[r.id] = true; });
  var visibleGeojson = {
    type: 'FeatureCollection',
    features: State.geojson.features.filter(function(f) { return !hiddenIds[f.properties.id]; })
  };
  State.geoLayer = L.geoJSON(visibleGeojson, {
    style: featureStyle,
    onEachFeature: function(feature, layer) {
      var rid = feature.properties.id;
      layer.on('mouseover', function() { if (State.selectedRegionId !== rid) layer.setStyle(hoverStyle(rid)); });
      layer.on('mouseout', function() { State.geoLayer.resetStyle(layer); layer.setStyle(featureStyle(feature)); });
      layer.on('click', function() { selectRegion(rid, true); });
      layer.bindTooltip(regionTooltipHTML(rid), { sticky: true, direction: 'top', className: 'region-tooltip', opacity: 1 });
    }
  }).addTo(State.map);
  
  if (State.visibility.map !== false) {
    State.map.getContainer().style.display = 'block';
  } else {
    State.map.getContainer().style.display = 'none';
  }
  
  fitMapToRegions();
  renderMapLegend();
  if (State.mapLabelsOn) showMapLabels();
}

function featureStyle(feature) {
  var isSelected = State.selectedRegionId === feature.properties.id;
  return {
    fillColor: colorForRegion(feature.properties.id),
    fillOpacity: isSelected ? 0.75 : 0.55,
    color: isSelected ? '#132036' : '#ffffff',
    weight: isSelected ? 2.5 : 1.4
  };
}

function hoverStyle(rid) {
  return { fillOpacity: 0.8, weight: 2, color: '#132036', fillColor: colorForRegion(rid) };
}

