/* ---------------------------------------------------------------------
   11b. Region boundary editing
   Lets you reshape a region's polygon by dragging its vertices right
   on the map — including regions loaded from regions.kml. Edits are
   stored separately (KEYS.boundaryEdits) and re-applied on top of the
   KML geometry every time it's loaded, so a fresh KML import won't
   silently wipe out a hand-tuned boundary.

   The number of points is NOT fixed to whatever the source KML had:
   - Small "+" handles sit on the midpoint of every edge — click one to
     insert a brand-new vertex there (splits that edge in two).
   - Double-click (or right-click) any solid vertex handle to remove it.
   This means a 6-point hexagon like Abha can be reshaped into as
   detailed a polygon as needed, with no upper limit on point count.
------------------------------------------------------------------- */
function toggleBoundaryEditing(regionId) {
  if (State.boundaryEditing && State.boundaryEditing.regionId === regionId) {
    saveBoundaryEdit();
    return;
  }
  if (State.boundaryEditing) {
    showToast('Finish or cancel the current boundary edit first.', 'err');
    return;
  }
  startBoundaryEdit(regionId);
}

function startBoundaryEdit(regionId) {
  var feature = State.geojson.features.find(function(f) { return f.properties.id === regionId; });
  if (!feature) return;

  var coords = feature.geometry.coordinates[0];
  // Drop the closing point (last === first) while editing; it's re-added on save.
  var openCoords = coords.length > 1 && coords[0][0] === coords[coords.length - 1][0] && coords[0][1] === coords[coords.length - 1][1]
    ? coords.slice(0, -1) : coords.slice();
  var latlngs = openCoords.map(function(c) { return L.latLng(c[1], c[0]); });

  // Dim the live polygon for this region so the edit outline reads clearly.
  if (State.geoLayer) {
    State.geoLayer.eachLayer(function(layer) {
      if (layer.feature.properties.id === regionId) layer.setStyle({ fillOpacity: 0.08, opacity: 0.25 });
    });
  }

  var editLayer = L.polygon(latlngs, { color: '#132036', weight: 2.5, fillOpacity: 0.12, dashArray: '5,4' }).addTo(State.map);
  var markerGroup = L.layerGroup().addTo(State.map);

  State.boundaryEditing = { regionId: regionId, editLayer: editLayer, markerGroup: markerGroup, latlngs: latlngs };

  refreshBoundaryHandles();
  State.map.fitBounds(editLayer.getBounds(), { padding: [60, 60] });

  var btn = document.getElementById('rp-edit-boundary');
  if (btn) {
    btn.textContent = 'Save boundary';
    btn.classList.remove('btn-sand');
    btn.classList.add('btn-primary');
  }
  showToast('Drag points to reshape ' + regionName(regionId) + ' · click "+" on an edge to add a point · double-click a point to remove it.', 'ok');
}

// Rebuilds every handle marker (vertex + midpoint "add point" handles)
// from the current State.boundaryEditing.latlngs array. Called on start,
// and after any add/remove so indices and midpoint positions stay correct.
function refreshBoundaryHandles() {
  var edit = State.boundaryEditing;
  if (!edit) return;
  edit.markerGroup.clearLayers();
  var latlngs = edit.latlngs;

  // Solid, draggable vertex handles — one per point, unlimited.
  latlngs.forEach(function(ll, i) {
    var handle = L.marker(ll, {
      draggable: true,
      icon: L.divIcon({ className: 'vertex-handle', iconSize: [14, 14], iconAnchor: [7, 7] })
    }).addTo(edit.markerGroup);
    handle.on('drag', function(e) {
      latlngs[i] = e.target.getLatLng();
      edit.editLayer.setLatLngs(latlngs);
    });
    handle.on('dragend', function() { refreshBoundaryHandles(); });
    handle.on('dblclick', function() { removeBoundaryVertex(i); });
    handle.on('contextmenu', function(e) {
      if (e.originalEvent) e.originalEvent.preventDefault();
      removeBoundaryVertex(i);
    });
  });

  // Small "+" midpoint handles on every edge (including the closing
  // edge back to point 0) — click to insert a new vertex there.
  latlngs.forEach(function(ll, i) {
    var next = latlngs[(i + 1) % latlngs.length];
    var mid = L.latLng((ll.lat + next.lat) / 2, (ll.lng + next.lng) / 2);
    var addHandle = L.marker(mid, {
      icon: L.divIcon({ className: 'vertex-handle vertex-handle-add', iconSize: [12, 12], iconAnchor: [6, 6], html: '+' })
    }).addTo(edit.markerGroup);
    addHandle.on('click', function() { insertBoundaryVertex(i + 1, mid); });
  });
}

function insertBoundaryVertex(index, latlng) {
  var edit = State.boundaryEditing;
  if (!edit) return;
  edit.latlngs.splice(index, 0, latlng);
  edit.editLayer.setLatLngs(edit.latlngs);
  refreshBoundaryHandles();
}

function removeBoundaryVertex(index) {
  var edit = State.boundaryEditing;
  if (!edit) return;
  if (edit.latlngs.length <= 3) {
    showToast('A boundary needs at least 3 points.', 'err');
    return;
  }
  edit.latlngs.splice(index, 1);
  edit.editLayer.setLatLngs(edit.latlngs);
  refreshBoundaryHandles();
}

function saveBoundaryEdit() {
  if (!State.boundaryEditing) return;
  var regionId = State.boundaryEditing.regionId;
  var latlngs = State.boundaryEditing.latlngs;
  if (latlngs.length < 3) {
    showToast('A boundary needs at least 3 points.', 'err');
    return;
  }
  var coords = latlngs.map(function(ll) { return [ll.lng, ll.lat]; });
  coords.push(coords[0]); // close the ring

  var feature = State.geojson.features.find(function(f) { return f.properties.id === regionId; });
  if (feature) feature.geometry.coordinates = [coords];

  State.boundaryEdits[regionId] = coords;
  DataStore.set(KEYS.boundaryEdits, State.boundaryEdits);
  DataStore.set(KEYS.geojson, State.geojson);

  endBoundaryEdit();
  buildGeoLayer();
  if (State.selectedRegionId === regionId) renderRegionPanel(regionId);
  showToast('Boundary saved for ' + regionName(regionId) + '.', 'ok');
}

function cancelBoundaryEdit() {
  if (!State.boundaryEditing) return;
  var regionId = State.boundaryEditing.regionId;
  endBoundaryEdit();
  buildGeoLayer();
  showToast('Boundary edit cancelled for ' + regionName(regionId) + '.', 'ok');
}

function endBoundaryEdit() {
  if (!State.boundaryEditing) return;
  State.map.removeLayer(State.boundaryEditing.editLayer);
  State.map.removeLayer(State.boundaryEditing.markerGroup);
  State.boundaryEditing = null;
  var btn = document.getElementById('rp-edit-boundary');
  if (btn) {
    btn.textContent = 'Edit boundary';
    btn.classList.remove('btn-primary');
    btn.classList.add('btn-sand');
  }
}

