/* ---------------------------------------------------------------------
   2. Storage: localStorage cache + remote sync (/api/state)
   -------------------------------------------------------------------
   localStorage alone is per-browser: it doesn't survive a cache clear
   and isn't shared across devices. So every DataStore.set() still
   writes to localStorage instantly (so the UI never waits on the
   network), but also pushes the change to a small serverless API
   backed by Vercel KV, which is what makes edits (boundaries, region
   names/colors, imported employees, labels, ...) show up on any
   device that opens the same deployment. If the API isn't reachable
   (running the site with `python3 -m http.server`, no KV configured
   yet, offline, etc.) everything quietly falls back to localStorage
   only — nothing breaks, it just stops syncing across devices.
------------------------------------------------------------------- */
const REMOTE_STATE_ENDPOINT = '/api/state';
let remoteSyncAvailable = true; // flips to false after a failed call, so we stop hammering a missing API
let pendingRemotePayload = {};
let remoteSyncTimer = null;

const DataStore = {
  get: function(key, fallback) {
    try {
      const val = localStorage.getItem(key);
      if (val === null) return fallback;
      return JSON.parse(val);
    } catch (e) {
      return fallback;
    }
  },
  set: function(key, value) {
    try {
      localStorage.setItem(key, JSON.stringify(value));
    } catch (e) {
      // localStorage full/unavailable — still try to sync remotely below
    }
    queueRemoteSync(key, value);
    return true;
  }
};

// Debounce remote writes: several DataStore.set() calls in the same
// tick (e.g. saving a boundary edit updates two keys) become one
// network request instead of several.
function queueRemoteSync(key, value) {
  if (!remoteSyncAvailable) return;
  pendingRemotePayload[key] = value;
  clearTimeout(remoteSyncTimer);
  remoteSyncTimer = setTimeout(flushRemoteSync, 500);
}

function flushRemoteSync() {
  const payload = pendingRemotePayload;
  pendingRemotePayload = {};
  if (!Object.keys(payload).length) return;
  fetch(REMOTE_STATE_ENDPOINT, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload)
  }).then(function(res) {
    if (!res.ok) throw new Error('bad status ' + res.status);
  }).catch(function(err) {
    console.warn('Remote sync unavailable (edits are still saved locally on this device):', err);
    remoteSyncAvailable = false;
  });
}

// Called once at startup, before bootstrap(), to pull the latest
// shared state down into localStorage so this device/browser picks
// up edits made anywhere else. Always resolves (never throws) so a
// missing/offline API can't block the app from loading.
function pullRemoteState() {
  const controller = new AbortController();
  const timeout = setTimeout(function() { controller.abort(); }, 3000);
  return fetch(REMOTE_STATE_ENDPOINT, { signal: controller.signal })
    .then(function(res) {
      if (!res.ok) throw new Error('bad status ' + res.status);
      return res.json();
    })
    .then(function(remote) {
      Object.keys(remote || {}).forEach(function(key) {
        try { localStorage.setItem(key, JSON.stringify(remote[key])); } catch (e) {}
      });
    })
    .catch(function(err) {
      console.warn('Could not reach remote state (using this device\'s local cache instead):', err);
      remoteSyncAvailable = false;
    })
    .finally(function() { clearTimeout(timeout); });
}

