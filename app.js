function getFilteredEmployees() {
  var search = State.employeeTable.search;
  var regionId = State.employeeTable.regionId;
  var status = State.employeeTable.status;
  var tier = State.employeeTable.tier;
  var thresholds = State.settings.thresholds;
  var filtered = [...State.employees];
  
  if (search) {
    var s = search.toLowerCase();
    filtered = filtered.filter(function(e) { return e.name.toLowerCase().includes(s) || e.id.toLowerCase().includes(s); });
  }
  if (regionId) filtered = filtered.filter(function(e) { return e.regionId === regionId; });
  if (status) filtered = filtered.filter(function(e) { return e.status === status; });
  if (tier) {
    filtered = filtered.filter(function(e) { return tierOf(e.productivity, thresholds) === tier; });
  }
  return filtered;
}

function renderEmployeesView() {
  var filtered = getFilteredEmployees();
  var sortKey = State.employeeTable.sortKey;
  var sortDir = State.employeeTable.sortDir;
  var page = State.employeeTable.page;
  var pageSize = State.employeeTable.pageSize;
  
  filtered.sort(function(a, b) {
    var va = a[sortKey] ?? '';
    var vb = b[sortKey] ?? '';
    if (typeof va === 'string') va = va.toLowerCase();
    if (typeof vb === 'string') vb = vb.toLowerCase();
    if (va < vb) return sortDir === 'asc' ? -1 : 1;
    if (va > vb) return sortDir === 'asc' ? 1 : -1;
    return 0;
  });

  var total = filtered.length;
  var totalPages = Math.max(1, Math.ceil(total / pageSize));
  var safePage = Math.min(page, totalPages);
  State.employeeTable.page = safePage;
  
  var start = (safePage - 1) * pageSize;
  var paginated = filtered.slice(start, start + pageSize);

  document.getElementById('emp-count-label').textContent = total + ' employees';

  var tbody = document.getElementById('emp-tbody');
  if (!paginated.length) {
    tbody.innerHTML = '<tr><td colspan="11" style="text-align:center;color:var(--ink-faint);padding:32px;">No employees match the current filters.</td></tr>';
  } else {
    tbody.innerHTML = paginated.map(function(e) {
      return '<tr>' +
        '<td><input type="checkbox" class="emp-row-check" data-id="' + e.id + '" ' + (State.employeeTable.selected.has(e.id) ? 'checked' : '') + '></td>' +
        '<td><div class="name-cell"><div class="avatar" style="width:28px;height:28px;font-size:10px;">' + initials(e.name) + '</div>' + e.name + '</div></td>' +
        '<td>' + regionName(e.regionId) + '</td>' +
        '<td><span style="color:' + (e.status === 'active' ? 'var(--r-good)' : 'var(--ink-faint)') + '">' + e.status + '</span></td>' +
        '<td>' + fmtProd(e.productivity) + '</td>' +
        '<td>' + fmtProd(e.productivityJul || e.productivity) + '</td>' +
        '<td>' + fmtProd(e.productivityAvg3m || e.productivity) + '</td>' +
        '<td>' + e.visits + '</td>' +
        '<td>' + e.completedTasks + '</td>' +
        '<td>' + e.projects + '</td>' +
        '<td>' +
          '<div class="row-actions">' +
            '<button class="icon-btn" data-action="edit" data-id="' + e.id + '" title="Edit"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M11 4H4a2 2 0 00-2 2v14a2 2 0 002 2h14a2 2 0 002-2v-7"/><path d="M18.5 2.5a2.121 2.121 0 013 3L12 15l-4 1 1-4 9.5-9.5z"/></svg></button>' +
            '<button class="icon-btn" data-action="delete" data-id="' + e.id + '" title="Delete"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M3 6h18M19 6v14a2 2 0 01-2 2H7a2 2 0 01-2-2V6m3 0V4a2 2 0 012-2h4a2 2 0 012 2v2"/></svg></button>' +
          '</div>' +
        '</td>' +
      '</tr>';
    }).join('');
  }

  var pagination = document.getElementById('emp-pagination');
  pagination.innerHTML = 
    '<span>' + total + ' employees · Page ' + safePage + ' of ' + totalPages + '</span>' +
    '<div class="pages">' +
      '<button class="page-btn" ' + (safePage <= 1 ? 'disabled' : '') + ' data-page="' + (safePage - 1) + '">‹</button>' +
      Array.from({ length: Math.min(5, totalPages) }, function(_, i) {
        var p = i + 1;
        if (totalPages > 5) {
          if (safePage <= 3) p = i + 1;
          else if (safePage >= totalPages - 2) p = totalPages - 4 + i;
          else p = safePage - 2 + i;
        }
        if (p < 1 || p > totalPages) return '';
        return '<button class="page-btn ' + (p === safePage ? 'active' : '') + '" data-page="' + p + '">' + p + '</button>';
      }).join('') +
      '<button class="page-btn" ' + (safePage >= totalPages ? 'disabled' : '') + ' data-page="' + (safePage + 1) + '">›</button>' +
    '</div>';

  pagination.querySelectorAll('.page-btn:not([disabled])').forEach(function(btn) {
    btn.addEventListener('click', function() {
      var p = parseInt(btn.dataset.page);
      if (p >= 1 && p <= totalPages) { State.employeeTable.page = p; renderEmployeesView(); }
    });
  });

  tbody.querySelectorAll('[data-action="edit"]').forEach(function(btn) {
    btn.addEventListener('click', function() {
      var emp = State.employees.find(function(e) { return e.id === btn.dataset.id; });
      if (emp) openEmployeeModal(emp);
    });
  });
  tbody.querySelectorAll('[data-action="delete"]').forEach(function(btn) {
    btn.addEventListener('click', function() {
      State.pendingDeleteId = btn.dataset.id;
      State.pendingBulkDeleteIds = null;
      var emp = State.employees.find(function(e) { return e.id === btn.dataset.id; });
      document.getElementById('confirm-body').textContent = 'Delete ' + (emp ? emp.name : 'this employee') + '?';
      document.getElementById('confirm-modal').classList.add('open');
    });
  });

  tbody.querySelectorAll('.emp-row-check').forEach(function(cb) {
    cb.addEventListener('change', function() {
      if (cb.checked) State.employeeTable.selected.add(cb.dataset.id);
      else State.employeeTable.selected.delete(cb.dataset.id);
      renderEmployeesView();
    });
  });

  // Header "select all" reflects the *filtered* set (every row matching
  // current search/region/status/tier filters, across all pages) —
  // checked if all of them are selected, indeterminate if only some are.
  var selectAllBox = document.getElementById('emp-select-all');
  if (selectAllBox) {
    var filteredIds = filtered.map(function(e) { return e.id; });
    var selectedInFilter = filteredIds.filter(function(id) { return State.employeeTable.selected.has(id); });
    selectAllBox.checked = filteredIds.length > 0 && selectedInFilter.length === filteredIds.length;
    selectAllBox.indeterminate = selectedInFilter.length > 0 && selectedInFilter.length < filteredIds.length;
  }

  updateBulkToolbar();

  document.querySelectorAll('thead th[data-sort]').forEach(function(th) {
    var arrow = th.querySelector('.arrow');
    if (th.dataset.sort === sortKey) {
      arrow.textContent = sortDir === 'asc' ? '▲' : '▼';
    } else {
      arrow.textContent = '';
    }
  });
}

